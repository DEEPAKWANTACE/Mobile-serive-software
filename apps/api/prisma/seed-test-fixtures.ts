import 'dotenv/config';
import { PrismaPg } from '@prisma/adapter-pg';
import { PrismaClient, type JobStatus, type Role } from '../src/generated/prisma/client.ts';
import { hashPassword } from '../src/lib/password.ts';

const prisma = new PrismaClient({ adapter: new PrismaPg({ connectionString: process.env.DATABASE_URL! }) });
const BRANCH_CODE = process.env.TEST_BRANCH_CODE ?? 'B1';
const PER_STATUS = Number(process.env.TEST_JOBS_PER_STATUS ?? 4);
const PASSWORD = process.env.TEST_ACCOUNTS_PASSWORD ?? 'a';

const STATUSES: JobStatus[] = [
  'RECEIVED', 'ASSIGNED', 'AWAITING_APPROVAL', 'IN_REPAIR', 'CUSTOMER_REJECTED', 'REPAIRED', 'TESTING',
  'READY_FOR_DELIVERY', 'SPARE_PENDING', 'RWR_PENDING', 'RWR', 'DELIVERED', 'CANCELLED',
];
const roles: Array<{ username: string; name: string; role: Role; global?: boolean }> = [
  { username: process.env.TEST_SA_USERNAME ?? 'sa', name: 'Test Super Admin', role: 'SUPER_ADMIN', global: true },
  { username: process.env.TEST_BM_USERNAME ?? 'bm', name: 'Test Branch Manager', role: 'BRANCH_MANAGER' },
  { username: process.env.TEST_CCO_USERNAME ?? 'cco', name: 'Test CCO', role: 'CCO' },
  { username: process.env.TEST_ENGINEER_USERNAME ?? 'eng', name: 'Test Engineer', role: 'ENGINEER' },
  { username: process.env.TEST_STORE_USERNAME ?? 'store', name: 'Test Storekeeper', role: 'STOREKEEPER' },
  { username: process.env.TEST_ACCOUNTS_USERNAME ?? 'acc', name: 'Test Accounts', role: 'ACCOUNTS' },
];
const minutesAgo = (minutes: number) => new Date(Date.now() - minutes * 60_000);
const minutesFromNow = (minutes: number) => new Date(Date.now() + minutes * 60_000);

async function main() {
  if (!Number.isInteger(PER_STATUS) || PER_STATUS < 1 || PER_STATUS > 10) throw new Error('TEST_JOBS_PER_STATUS must be between 1 and 10');
  const branch = await prisma.branch.findUnique({ where: { code: BRANCH_CODE } });
  if (!branch) throw new Error(`Test branch ${BRANCH_CODE} does not exist. Run db:seed-test-accounts first.`);
  if (BRANCH_CODE !== 'B1' && !branch.name.toLowerCase().includes('test')) {
    throw new Error(`Refusing to seed non-test branch ${branch.code} (${branch.name})`);
  }

  const passwordHash = await hashPassword(PASSWORD);
  const users = new Map<string, { id: string; name: string; role: Role; branchId: string | null }>();
  for (const def of roles) {
    const row = await prisma.user.upsert({
      where: { username: def.username },
      update: { name: def.name, role: def.role, branchId: def.global ? null : branch.id, passwordHash, passwordChangedAt: new Date(), isActive: true },
      create: { username: def.username, name: def.name, role: def.role, branchId: def.global ? null : branch.id, passwordHash, passwordChangedAt: new Date(), isActive: true },
      select: { id: true, name: true, role: true, branchId: true },
    });
    users.set(def.username, row);
  }
  const getUser = (username: string) => {
    const user = users.get(username);
    if (!user) throw new Error(`Missing test user ${username}`);
    return user;
  };
  const bm = getUser(process.env.TEST_BM_USERNAME ?? 'bm');
  const cco = getUser(process.env.TEST_CCO_USERNAME ?? 'cco');
  const engineer = getUser(process.env.TEST_ENGINEER_USERNAME ?? 'eng');

  const fault = (await prisma.fault.findFirst({ where: { branchId: branch.id, name: '[TEST] General repair' } }))
    ?? (await prisma.fault.create({ data: { branchId: branch.id, name: '[TEST] General repair', description: 'Fixture fault generated by seed-test-fixtures.ts' } }));

  let jobCount = 0;
  for (const [statusIndex, status] of STATUSES.entries()) {
    for (let variant = 1; variant <= PER_STATUS; variant++) {
      const sequence = 910001 + statusIndex * PER_STATUS + variant - 1;
      const jobNumber = `TSTFIX-${sequence}`;
      const customer = await prisma.customer.upsert({
        where: { phone: `9${String(sequence).padStart(9, '0').slice(-9)}` },
        update: { name: `[TEST] ${status.replaceAll('_', ' ')} Customer ${variant}`, city: 'Test City' },
        create: { phone: `9${String(sequence).padStart(9, '0').slice(-9)}`, name: `[TEST] ${status.replaceAll('_', ' ')} Customer ${variant}`, city: 'Test City', address: 'Fixture address, Test City' },
      });
      const createdAt = minutesAgo(60 * 24 * (variant + 1) + statusIndex * 15);
      const assigned = status !== 'RECEIVED' && status !== 'CANCELLED';
      const diagnosed = !['RECEIVED', 'ASSIGNED', 'CANCELLED'].includes(status);
      const approved = ['IN_REPAIR', 'REPAIRED', 'TESTING', 'READY_FOR_DELIVERY', 'SPARE_PENDING', 'DELIVERED'].includes(status);
      const repaired = ['REPAIRED', 'TESTING', 'READY_FOR_DELIVERY', 'DELIVERED'].includes(status);
      const ready = ['READY_FOR_DELIVERY', 'DELIVERED'].includes(status);
      const rwr = status === 'RWR';
      const closed = status === 'DELIVERED' || status === 'CANCELLED';
      const dueAt = closed || ready || rwr ? null : variant === 1 ? minutesAgo(30) : variant === 2 ? minutesFromNow(15) : variant === 3 ? minutesFromNow(120) : minutesFromNow(24 * 60);

      const job = await prisma.job.upsert({
        where: { jobNumber },
        update: {
          branchId: branch.id, currentBranchId: branch.id, customerId: customer.id, status, dueAt,
          assignedEngineerId: assigned ? engineer.id : null, assignedAt: assigned ? createdAt : null,
          diagnosisNotes: diagnosed ? `[FIXTURE] Diagnosis for ${status}` : null, diagnosedAt: diagnosed ? minutesAgo(90) : null,
          quotedAmount: diagnosed ? 1500 + variant * 250 : null, approvedAmount: approved ? 1500 + variant * 250 : null,
          approvedAt: approved ? minutesAgo(60) : null, approvedById: approved ? cco.id : null,
          customerResponse: status === 'CUSTOMER_REJECTED' ? 'Fixture customer rejected estimate' : approved ? 'Fixture customer approved estimate' : null,
          repairedAt: repaired ? minutesAgo(45) : null, testingAt: status === 'TESTING' ? minutesAgo(20) : null,
          readyAt: ready ? minutesAgo(30) : null, sparePart: status === 'SPARE_PENDING' ? 'Fixture display assembly' : null,
          spareRequestedAt: status === 'SPARE_PENDING' ? minutesAgo(180) : null,
          rwrReason: status === 'RWR_PENDING' || status === 'RWR' ? 'NOT_REPAIRABLE' : null,
          rwrNote: status === 'RWR_PENDING' || status === 'RWR' ? 'Fixture RWR scenario' : null,
          rwrAt: rwr ? minutesAgo(30) : null, deliveredAt: status === 'DELIVERED' ? minutesAgo(15) : null,
          deliveredById: status === 'DELIVERED' ? cco.id : null, deliveredTo: status === 'DELIVERED' ? 'Fixture Customer' : null,
          cancelledAt: status === 'CANCELLED' ? minutesAgo(20) : null, cancelReason: status === 'CANCELLED' ? 'Fixture cancellation' : null,
          updatedAt: new Date(),
        },
        create: {
          jobNumber, branchId: branch.id, currentBranchId: branch.id, customerId: customer.id, createdById: cco.id, inwardById: cco.id,
          status, dueAt, createdAt, jobType: 'MOBILE', manualBrand: '[TEST] Demo Brand', manualModel: `Status ${status} ${variant}`,
          imei: `35${String(sequence).padStart(13, '0').slice(-13)}`, color: ['Black', 'Blue', 'Silver', 'Red'][variant - 1] ?? 'Black',
          customerComplaint: `[FIXTURE] Complaint exercising ${status}`, conditionNotes: 'Fixture device in used condition', accessories: ['SIM Tray'],
          estimatedAmount: 1200 + variant * 200, assignedEngineerId: assigned ? engineer.id : null, assignedAt: assigned ? createdAt : null,
          diagnosisNotes: diagnosed ? `[FIXTURE] Diagnosis for ${status}` : null, diagnosedAt: diagnosed ? minutesAgo(90) : null,
          quotedAmount: diagnosed ? 1500 + variant * 250 : null, approvedAmount: approved ? 1500 + variant * 250 : null,
          approvedAt: approved ? minutesAgo(60) : null, approvedById: approved ? cco.id : null,
          customerResponse: status === 'CUSTOMER_REJECTED' ? 'Fixture customer rejected estimate' : approved ? 'Fixture customer approved estimate' : null,
          repairedAt: repaired ? minutesAgo(45) : null, testingAt: status === 'TESTING' ? minutesAgo(20) : null,
          readyAt: ready ? minutesAgo(30) : null, sparePart: status === 'SPARE_PENDING' ? 'Fixture display assembly' : null,
          spareRequestedAt: status === 'SPARE_PENDING' ? minutesAgo(180) : null,
          rwrReason: status === 'RWR_PENDING' || status === 'RWR' ? 'NOT_REPAIRABLE' : null,
          rwrNote: status === 'RWR_PENDING' || status === 'RWR' ? 'Fixture RWR scenario' : null, rwrAt: rwr ? minutesAgo(30) : null,
          deliveredAt: status === 'DELIVERED' ? minutesAgo(15) : null, deliveredById: status === 'DELIVERED' ? cco.id : null,
          deliveredTo: status === 'DELIVERED' ? 'Fixture Customer' : null,
          cancelledAt: status === 'CANCELLED' ? minutesAgo(20) : null, cancelReason: status === 'CANCELLED' ? 'Fixture cancellation' : null,
        },
      });

      await prisma.$transaction([
        prisma.jobFault.deleteMany({ where: { jobId: job.id } }),
        prisma.jobEstimateLine.deleteMany({ where: { jobId: job.id } }),
        prisma.jobStatusHistory.deleteMany({ where: { jobId: job.id } }),
        prisma.jobAssignment.deleteMany({ where: { jobId: job.id } }),
        prisma.payment.deleteMany({ where: { jobId: job.id } }),
      ]);
      await prisma.jobFault.create({ data: { jobId: job.id, faultId: fault.id, priceLabel: 'Fixture price', price: 1200 + variant * 200 } });
      if (diagnosed) await prisma.jobEstimateLine.create({ data: { jobId: job.id, description: `[FIXTURE] Repair for ${status}`, amount: 1500 + variant * 250 } });
      await prisma.jobStatusHistory.create({ data: { jobId: job.id, toStatus: status, engineerId: assigned ? engineer.id : null, changedById: status === 'AWAITING_APPROVAL' ? engineer.id : cco.id, remark: `[FIXTURE] Current status ${status}`, changedAt: createdAt } });
      if (assigned) await prisma.jobAssignment.create({ data: { jobId: job.id, engineerId: engineer.id, assignedById: cco.id, assignedAt: createdAt, ...(closed && { endedAt: minutesAgo(15), endReason: 'CLOSED' }) } });
      if (variant % 2 === 0 && status !== 'CANCELLED') await prisma.payment.create({ data: { jobId: job.id, branchId: branch.id, kind: 'ADVANCE', mode: variant % 4 === 0 ? 'UPI' : 'CASH', amount: 500, reference: variant % 4 === 0 ? `FIXTURE-${sequence}` : null, receivedById: cco.id, createdAt } });
      jobCount += 1;
    }
  }

  await prisma.reminder.deleteMany({ where: { title: { startsWith: '[FIXTURE]' }, OR: [{ branchId: branch.id }, { createdById: getUser(process.env.TEST_SA_USERNAME ?? 'sa').id }] } });
  let reminderCount = 0;
  for (const def of roles) {
    const assignee = getUser(def.username);
    const creator = def.role === 'SUPER_ADMIN' || def.role === 'BRANCH_MANAGER' ? assignee : bm;
    const branchId = assignee.branchId;
    const reminders = [
      { title: `[FIXTURE] ${def.role} overdue follow-up`, dueAt: minutesAgo(10) },
      { title: `[FIXTURE] ${def.role} call customer in 15 minutes`, dueAt: minutesFromNow(15) },
      { title: `[FIXTURE] ${def.role} approval task in 2 hours`, dueAt: minutesFromNow(120) },
      { title: `[FIXTURE] ${def.role} order part tomorrow`, dueAt: minutesFromNow(24 * 60) },
      { title: `[FIXTURE] ${def.role} completed example`, dueAt: minutesAgo(120), completedAt: minutesAgo(60) },
    ];
    for (const reminder of reminders) {
      await prisma.reminder.create({ data: { ...reminder, createdById: creator.id, assignedToId: assignee.id, branchId } });
      reminderCount += 1;
    }
  }

  console.log(JSON.stringify({ branch: `${branch.code} - ${branch.name}`, users: roles.map((role) => role.username), statuses: STATUSES.length, jobsPerStatus: PER_STATUS, jobs: jobCount, reminders: reminderCount }, null, 2));
}

main()
  .catch((error) => { console.error(error); process.exitCode = 1; })
  .finally(() => prisma.$disconnect());
